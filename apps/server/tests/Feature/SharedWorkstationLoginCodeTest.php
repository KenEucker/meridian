    /*
    |--------------------------------------------------------------------------
    | Redaction (technical spec 13.2; data/API 12.4)
    |--------------------------------------------------------------------------
    */

    /**
     * "Raw login codes are not logged" (data/API 12.4). The plaintext exists in
     * the response that generated it and nowhere else — not in the row, not in an
     * audit entry, not in the log.
     */
    public function test_no_raw_code_reaches_the_database_an_audit_entry_or_the_log(): void
    {
        Log::spy();

        $workstation = $this->workstation();
        $user = User::factory()->create();

        $response = $this->requestCode($this->signedIn($user), [
            'shared_workstation_id' => $workstation->getKey(),
        ])->assertStatus(201);

        $formatted = (string) $response->json('code');
        $normalized = SharedWorkstationLoginCodeGenerator::normalize($formatted);

        $record = SharedWorkstationLoginCode::query()->sole();

        // Reach the rest of a code's audited life before asserting.
        $this->service()->redeem($workstation, $formatted);

        $storedRow = (string) json_encode($record->fresh()?->getAttributes());
        $audited = $this->auditText();

        $this->assertNotSame('', $audited);

        foreach ([$storedRow, $audited] as $haystack) {
            $this->assertStringNotContainsString($formatted, $haystack);
            $this->assertStringNotContainsString($normalized, $haystack);
        }

        // Not even the stored hash reaches an audit entry: entries name the code
        // by identifier and by scope.
        $this->assertStringNotContainsString($record->code_hash, $audited);
        $this->assertStringContainsString((string) $record->getKey(), $audited);

        Log::shouldNotHaveReceived('info');
        Log::shouldNotHaveReceived('debug');
        Log::shouldNotHaveReceived('warning');
        Log::shouldNotHaveReceived('error');
    }

    public function test_only_a_keyed_hash_of_a_code_is_stored(): void
    {
        $issued = $this->service()->generateForUser(
            User::factory()->create(),
            User::factory()->create(),
            $this->workstation(),
        );

        $record = SharedWorkstationLoginCode::query()->sole();

        $this->assertNotSame($issued->plaintextCode, $record->code_hash);
        $this->assertSame(
            SharedWorkstationLoginCodeGenerator::hash($issued->plaintextCode),
            $record->code_hash,
        );

        // Keyed to this application, so a stolen table cannot be turned into a
        // rainbow table, and namespaced away from the API login code hash so a
        // hash cannot be carried between the two credentials.
        $this->assertNotSame(
            hash('sha256', $issued->plaintextCode),
            $record->code_hash,
        );
        $this->assertNotSame(
            ApiLoginCodeGenerator::hash($issued->plaintextCode),
            $record->code_hash,
        );
    }

