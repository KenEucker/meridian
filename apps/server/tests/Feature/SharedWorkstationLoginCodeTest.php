    /**
     * A new code for the same user and workstation replaces the one they held, so
     * a forgotten code does not leave a second six-week credential live.
     */
    public function test_generating_a_code_retires_the_users_outstanding_code_for_that_workstation(): void
    {
        $workstation = $this->workstation();
        $user = User::factory()->create();
        $operator = User::factory()->create();

        $first = $this->service()->generateForUser($user, $operator, $workstation)->record;
        $second = $this->service()->generateForUser($user, $operator, $workstation)->record;

        $this->assertNotNull($first->fresh()->revoked_at);
        $this->assertNull($second->fresh()->revoked_at);

        $audit = AuditEvent::query()
            ->where('action', SharedWorkstationLoginCodeService::AUDIT_REVOKED)
            ->sole();

        $this->assertSame(SharedWorkstationLoginCodeService::REASON_SUPERSEDED, $audit->reason);
        $this->assertSame((string) $first->getKey(), $audit->entity_id);
    }

    public function test_a_code_for_another_workstation_is_left_alone(): void
