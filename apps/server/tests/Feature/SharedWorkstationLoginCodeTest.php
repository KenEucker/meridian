    public function test_a_code_signs_in_the_user_it_was_generated_for_and_is_then_spent(): void
    {
        $workstation = $this->workstation();
        $subject = User::factory()->create();

        $issued = $this->service()->generateForUser($subject, User::factory()->create(), $workstation);

        // Typed as a person types it: with the presentation dash, in lower case.
        $redeemed = $this->service()->redeem($workstation, strtolower($issued->formattedCode()));

        $this->assertSame($subject->getKey(), $redeemed->user_id);
        $this->assertNotNull($redeemed->used_at);

        try {
            $this->service()->redeem($workstation, $issued->plaintextCode);
            $this->fail('A used code should not sign anybody in again.');
        } catch (SharedWorkstationLoginException $exception) {
            $this->assertSame(SharedWorkstationLoginException::REASON_INVALID_CODE, $exception->reason);
        }
    }

    /**
     * A code held by someone who has since been disabled does not sign them in.
     * The code is spent rather than handed back, as the mailed API login code is:
     * the refusal is about the account, not about possession of the code.
     */
    public function test_a_code_for_a_since_disabled_account_does_not_sign_anybody_in(): void
    {
        $workstation = $this->workstation();
        $subject = User::factory()->create();

        $issued = $this->service()->generateForUser($subject, User::factory()->create(), $workstation);

        $subject->forceFill(['disabled_at' => now()])->save();

        try {
            $this->service()->redeem($workstation, $issued->plaintextCode);
            $this->fail('A disabled account should not be signed in by a code.');
        } catch (SharedWorkstationLoginException $exception) {
            $this->assertSame(SharedWorkstationLoginException::REASON_ACCOUNT_DISABLED, $exception->reason);
        }

        $this->assertNotNull($issued->record->fresh()->used_at);
        $this->assertSame(0, AuditEvent::query()
            ->where('action', SharedWorkstationLoginCodeService::AUDIT_USED)
            ->count());
    }

