                $this->fail('An untrusted workstation should not be issued a login code.');
            } catch (SharedWorkstationLoginException $exception) {
                $this->assertSame(
                    SharedWorkstationLoginException::REASON_WORKSTATION_UNTRUSTED,
                    $exception->reason,
                );
            }
        }

        $this->assertSame(0, SharedWorkstationLoginCode::query()->count());
    }

