    public function test_an_untrusted_or_revoked_workstation_is_refused_a_code(): void
    {
        foreach ([
            SharedWorkstation::factory()->untrusted(),
            SharedWorkstation::factory()->revoked(),
        ] as $state) {
            $event = Event::factory()->create();
            $workstation = $state->create([
                'organization_id' => $event->organization_id,
                'event_id' => $event->getKey(),
            ]);

            try {
                $this->service()->generateForUser(
                    User::factory()->create(),
                    User::factory()->create(),
                    $workstation,
