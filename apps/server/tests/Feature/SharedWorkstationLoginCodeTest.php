/**
 * Shared-workstation login code generation, entry, rate limiting, and audit
 * (M16.8).
 *
 * Source: AUTH-026 through AUTH-029; technical spec 13.2; data/API 12.4. Codes
 * are generated by God mode for any known user and by a user for themselves from
 * a device where they already hold a session; they are scoped to one user, one
 * event, and one trusted shared workstation, are valid six weeks, are stored only
 * as keyed hashes, and are audited when generated and when used.
 *
 * The session a code establishes — technical spec 13.3 — is M16.9 and is not
 * asserted here beyond the rule that entry issues no API token.
 */
class SharedWorkstationLoginCodeTest extends TestCase
{
    use RefreshDatabase;

    private function service(): SharedWorkstationLoginCodeService
    {
        return app(SharedWorkstationLoginCodeService::class);
    }

    /**
     * A trusted shared workstation pinned to a real event, which is the only
     * state a code can be scoped to (technical spec 13.1).
     */
    private function workstation(array $attributes = []): SharedWorkstation
    {
        $event = Event::factory()->create();

        return SharedWorkstation::factory()->create([
            'organization_id' => $event->organization_id,
            'event_id' => $event->getKey(),
            ...$attributes,
        ]);
    }

    /**
     * A user holding a live API session, as a person's own phone does.
     */
    private function signedIn(User $user, ?Device $device = null): string
    {
        return app(ApiTokenIssuer::class)
            ->issue($user, $device ?? Device::factory()->create(), 'Meridian Field')
            ->plainTextToken;
    }

    private function requestCode(string $token, array $payload): TestResponse
    {
        $this->app['auth']->forgetGuards();

        return $this->withHeader('Authorization', 'Bearer '.$token)
            ->postJson(route('api.auth.shared-workstation-login-code.store'), $payload);
    }

    /**
     * Every stored audit row as text, for asserting what is in none of them.
     */
    private function auditText(): string
    {
        return AuditEvent::query()
            ->get()
            ->map(fn (AuditEvent $event): string => (string) json_encode($event->getAttributes()))
            ->implode("\n");
    }

    /*
    |--------------------------------------------------------------------------
    | Generation authority (AUTH-026, AUTH-028)
    |--------------------------------------------------------------------------
    */

    public function test_god_mode_generates_a_code_for_another_user(): void
    {
        $workstation = $this->workstation();
        $subject = User::factory()->create();
        $operator = User::factory()->create();

        $issued = $this->service()->generateForUser($subject, $operator, $workstation);

        $record = SharedWorkstationLoginCode::query()->sole();

        $this->assertSame($subject->getKey(), $record->user_id);
        $this->assertSame($operator->getKey(), $record->generated_by_user_id);
        $this->assertSame($workstation->getKey(), $record->shared_workstation_id);
        $this->assertSame($workstation->event_id, $record->event_id);
        $this->assertSame($record->getKey(), $issued->record->getKey());
    }

    public function test_a_user_generates_a_code_for_themselves_from_a_device_holding_a_session(): void
    {
        $workstation = $this->workstation();
        $user = User::factory()->create();
        $device = Device::factory()->create();

        $response = $this->requestCode($this->signedIn($user, $device), [
            'shared_workstation_id' => $workstation->getKey(),
        ]);

        $response->assertStatus(201);
        $response->assertJsonPath('user.id', $user->getKey());
        $response->assertJsonPath('shared_workstation.id', $workstation->getKey());
        $response->assertJsonPath('event_id', $workstation->event_id);

        $record = SharedWorkstationLoginCode::query()->sole();

        // AUTH-028: a self-service code is scoped to the generating user, which
        // is what `generated_by_user_id === user_id` records (data/API 12.4).
        $this->assertSame($user->getKey(), $record->user_id);
        $this->assertSame($user->getKey(), $record->generated_by_user_id);

        // The code that came back is the code that was stored, and the response
        // is the only place it exists.
        $code = (string) $response->json('code');
        $this->assertSame(SharedWorkstationLoginCodeGenerator::hash($code), $record->code_hash);
    }

    public function test_a_user_cannot_generate_a_code_for_someone_else(): void
    {
        $workstation = $this->workstation();
        $user = User::factory()->create();
        $someoneElse = User::factory()->create();

        $response = $this->requestCode($this->signedIn($user), [
            'shared_workstation_id' => $workstation->getKey(),
            'user_id' => $someoneElse->getKey(),
        ]);

        $response->assertStatus(403);
        $response->assertJsonPath('reason', SharedWorkstationLoginException::REASON_SELF_SERVICE_SCOPE);

        $this->assertSame(0, SharedWorkstationLoginCode::query()->count());
    }

    /**
     * The endpoint has no user field to abuse, and the domain refuses the same
     * thing independently, so a second caller cannot reintroduce it.
     */
    public function test_the_domain_refuses_self_service_generation_for_another_user(): void
    {
        $workstation = $this->workstation();
        $subject = User::factory()->create();
        $other = User::factory()->create();

        try {
            $this->service()->generate(
                subject: $subject,
                generatedBy: $other,
                workstation: $workstation,
                authority: SharedWorkstationLoginCodeService::AUTHORITY_SELF_SERVICE,
            );
            $this->fail('Self-service generation for another user should be refused.');
        } catch (SharedWorkstationLoginException $exception) {
            $this->assertSame(SharedWorkstationLoginException::REASON_SELF_SERVICE_SCOPE, $exception->reason);
        }

        $this->assertSame(0, SharedWorkstationLoginCode::query()->count());
    }

    public function test_generating_a_code_requires_a_session(): void
    {
        $workstation = $this->workstation();

        $this->postJson(route('api.auth.shared-workstation-login-code.store'), [
            'shared_workstation_id' => $workstation->getKey(),
