    /*
    |--------------------------------------------------------------------------
    | Rate limiting (AUTH-029)
    |--------------------------------------------------------------------------
    */

    public function test_generation_is_rate_limited_per_user(): void
    {
        config()->set('meridian.shared_workstation_login_codes.generation_per_user_per_hour', 2);

        $workstation = $this->workstation();
        $user = User::factory()->create();
        $token = $this->signedIn($user);

        $this->requestCode($token, ['shared_workstation_id' => $workstation->getKey()])->assertStatus(201);
        $this->requestCode($token, ['shared_workstation_id' => $workstation->getKey()])->assertStatus(201);

        $refused = $this->requestCode($token, ['shared_workstation_id' => $workstation->getKey()]);

        $refused->assertStatus(429);
        $refused->assertJsonPath('reason', SharedWorkstationLoginException::REASON_RATE_LIMITED);
        $refused->assertHeader('Retry-After');

        // The limit is keyed to the user a code is for, so a second person is
        // unaffected by the first person's burst.
        $this->requestCode($this->signedIn(User::factory()->create()), [
            'shared_workstation_id' => $workstation->getKey(),
        ])->assertStatus(201);
    }

    public function test_generation_is_rate_limited_per_node(): void
    {
        config()->set('meridian.shared_workstation_login_codes.generation_per_node_per_hour', 2);

        $workstation = $this->workstation();
        $operator = User::factory()->create();

        $this->service()->generateForUser(User::factory()->create(), $operator, $workstation);
        $this->service()->generateForUser(User::factory()->create(), $operator, $workstation);

        try {
            $this->service()->generateForUser(User::factory()->create(), $operator, $workstation);
            $this->fail('The node-wide generation limit should have refused a third code.');
        } catch (SharedWorkstationLoginException $exception) {
            $this->assertSame(SharedWorkstationLoginException::REASON_RATE_LIMITED, $exception->reason);
        }

        $this->assertSame(2, SharedWorkstationLoginCode::query()->count());
    }

    public function test_code_entry_is_rate_limited_per_workstation(): void
    {
        config()->set('meridian.shared_workstation_login_codes.entry_attempts_per_workstation_per_minute', 2);

        $workstation = $this->workstation();
        $other = $this->workstation();

        foreach (['WRONGCOD', 'WRONGCDE'] as $guess) {
            try {
                $this->service()->redeem($workstation, $guess);
            } catch (SharedWorkstationLoginException $exception) {
                $this->assertSame(SharedWorkstationLoginException::REASON_INVALID_CODE, $exception->reason);
            }
        }

        try {
            $this->service()->redeem($workstation, 'WRONGCDF');
            $this->fail('A third attempt at this workstation should have been rate limited.');
        } catch (SharedWorkstationLoginException $exception) {
            $this->assertSame(SharedWorkstationLoginException::REASON_RATE_LIMITED, $exception->reason);
        }

        // Guessing at one workstation does not lock out another.
        try {
            $this->service()->redeem($other, 'WRONGCDG');
            $this->fail('An unknown code should be refused.');
        } catch (SharedWorkstationLoginException $exception) {
            $this->assertSame(SharedWorkstationLoginException::REASON_INVALID_CODE, $exception->reason);
        }
    }

