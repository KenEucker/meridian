(function () {
    'use strict';

    var sourceSelector = '[data-meridian-slug-target]';

    function fields() {
        return Array.from(document.querySelectorAll('input, textarea, select'));
    }

    function fieldByName(name) {
        return fields().find(function (field) {
            return field.name === name;
        }) || null;
    }

    function slugify(value) {
        return value
            .toString()
            .normalize('NFKD')
            .replace(/[\u0300-\u036f]/g, '')
            .toLowerCase()
            .replace(/[^a-z0-9]+/g, '-')
            .replace(/^-+|-+$/g, '')
            .replace(/-{2,}/g, '-');
    }

    function yearFrom(value) {
        var match = value ? value.toString().match(/\b(19|20)\d{2}\b/) : null;

        return match ? match[0] : '';
    }

    function buildValue(source) {
        var generated = slugify(source.value || '');
        var yearSourceName = source.dataset.meridianSlugYearSource;
        var yearSource = yearSourceName ? fieldByName(yearSourceName) : null;
        var year = yearSource ? yearFrom(yearSource.value) : '';

        if (year && generated && !generated.endsWith('-' + year)) {
            generated = generated + '-' + year;
        }

        if (source.dataset.meridianSlugFormat === 'code') {
            return generated.toUpperCase();
        }

        return generated;
    }

    function canReplace(target) {
        return target.value.trim() === '' || target.dataset.meridianAutoGenerated === 'true';
    }

    function generate(source) {
        var target = fieldByName(source.dataset.meridianSlugTarget);

        if (!target || !canReplace(target)) {
            return;
        }

        var generated = buildValue(source);

        if (generated === '') {
            return;
        }

        target.value = generated;
        target.dataset.meridianAutoGenerated = 'true';
        target.dataset.meridianApplyingAutoGenerated = 'true';
        target.dispatchEvent(new Event('input', { bubbles: true }));
        delete target.dataset.meridianApplyingAutoGenerated;
    }

    function bind(source) {
        if (source.dataset.meridianSlugBound === 'true') {
            return;
        }

        source.dataset.meridianSlugBound = 'true';

        var target = fieldByName(source.dataset.meridianSlugTarget);
        var yearSourceName = source.dataset.meridianSlugYearSource;
        var yearSource = yearSourceName ? fieldByName(yearSourceName) : null;

        source.addEventListener('blur', function () {
            generate(source);
        });

        if (target) {
            target.addEventListener('input', function () {
                if (target.dataset.meridianApplyingAutoGenerated === 'true') {
                    return;
                }

                target.dataset.meridianAutoGenerated = 'false';
            });
        }

        if (yearSource) {
            yearSource.addEventListener('blur', function () {
                generate(source);
            });
            yearSource.addEventListener('change', function () {
                generate(source);
            });
        }
    }

    function boot() {
        document.querySelectorAll(sourceSelector).forEach(bind);
    }

    document.addEventListener('DOMContentLoaded', boot);
    document.addEventListener('turbo:load', boot);
})();
